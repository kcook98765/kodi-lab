"""Real manifest/copy guards with disposable tar-backed Docker fixtures."""

import io
import tarfile
from contextlib import nullcontext
from dataclasses import replace
from pathlib import Path
from typing import Any
from uuid import uuid4

import pytest

from kodi_lab.broker.docker_inventory import DockerManagedContainerAdapter
from kodi_lab.broker.errors import (
    DockerDevelopmentSourceDeploymentError,
    RuntimeRevisionPreconditionError,
)
from kodi_lab.development.addition_reviews import SourceAdditionProof
from kodi_lab.domain import DevelopmentSourceDeploymentConfidence
from tests.broker import test_development_source_deployment as fixture

PATH = "resources/generated.xml"
PAYLOAD = b"generated bytes are preserved exactly"


def prepared(tmp_path: Path) -> tuple[Any, Any, Any, SourceAdditionProof]:
    spec = fixture._spec(tmp_path)
    client = fixture.FakeDeploymentDockerClient()
    baseline = fixture._apply(client, spec)
    spec = replace(
        spec,
        prior_evidence=fixture._prior(baseline),
        deployment_operation_id=str(uuid4()),
        addition_scope_digest="sha256:" + "a" * 64,
    )
    client.entries[PATH] = (PAYLOAD, 0o644, 42, 43)
    (spec.development_root / "addon/resources/changed.py").write_text(
        "candidate changes"
    )
    proof = DockerManagedContainerAdapter(lambda: client).review_source_additions(
        spec=spec, expected_container_id=fixture.CONTAINER_ID, paths=(PATH,)
    )
    client.put_members.clear()
    client.applied = False
    return client, spec, baseline, proof


def approved(spec: Any, proof: SourceAdditionProof) -> Any:
    return replace(
        spec,
        approved_additions=proof,
        approval_check=lambda: None,
        approval_guard=nullcontext,
    )


def test_default_refusal_and_explicit_exact_copy_preserves_generated_bytes(
    tmp_path: Path,
) -> None:
    client, spec, baseline, proof = prepared(tmp_path)
    assert proof.trusted_destination_digest == baseline.verified_destination_digest
    assert proof.additions[0].size == len(PAYLOAD)
    with pytest.raises(DockerDevelopmentSourceDeploymentError) as refused:
        fixture._apply(client, spec)
    assert refused.value.code == "development_source_replacement_conflict"
    assert client.put_members == []
    result = fixture._apply(client, approved(spec, proof))
    assert client.entries[PATH] == (PAYLOAD, 0o644, 42, 43)
    assert result.verified_destination_digest == client.current_digest()
    assert result.source_manifest_digest != result.verified_destination_digest
    assert result.destination_only_count == 1
    assert all(PATH not in members for members in client.put_members)


@pytest.mark.parametrize(
    "drift",
    [
        "modify_original",
        "delete_original",
        "original_mode",
        "original_owner",
        "added_content",
        "added_mode",
        "added_owner",
        "delete_added",
        "extra_file",
        "extra_directory",
        "candidate_collision",
        "candidate_directory_collision",
        "candidate_change",
        "scope_change",
        "image_change",
        "container_change",
        "runtime_change",
        "approval_exclusion_absent",
    ],
)
def test_approval_fails_closed_after_any_relevant_change(
    tmp_path: Path, drift: str
) -> None:
    client, spec, _baseline, proof = prepared(tmp_path)
    if drift == "modify_original":
        client.entries["unchanged.py"] = (b"tampered", 0o644, 42, 43)
    elif drift == "delete_original":
        del client.entries["unchanged.py"]
    elif drift == "original_mode":
        content, _, uid, gid = client.entries["unchanged.py"]
        client.entries["unchanged.py"] = (content, 0o755, uid, gid)
    elif drift == "original_owner":
        content, mode, _, gid = client.entries["unchanged.py"]
        client.entries["unchanged.py"] = (content, mode, 99, gid)
    elif drift == "added_content":
        client.entries[PATH] = (b"replaced", 0o644, 42, 43)
    elif drift == "added_mode":
        client.entries[PATH] = (PAYLOAD, 0o755, 42, 43)
    elif drift == "added_owner":
        client.entries[PATH] = (PAYLOAD, 0o644, 99, 43)
    elif drift == "delete_added":
        del client.entries[PATH]
    elif drift == "extra_file":
        client.entries["resources/another.xml"] = (b"unknown", 0o644, 42, 43)
    elif drift == "extra_directory":
        client.entries["resources/new-directory"] = (None, 0o755, 42, 43)
    elif drift == "candidate_collision":
        (spec.development_root / "addon" / PATH).write_bytes(PAYLOAD)
    elif drift == "candidate_directory_collision":
        (spec.development_root / "addon" / PATH).mkdir()
    elif drift == "candidate_change":
        (spec.development_root / "addon/resources/changed.py").write_text(
            "changed after preview"
        )
    elif drift == "scope_change":
        spec = replace(spec, addition_scope_digest="sha256:" + "b" * 64)
    elif drift == "image_change":
        client.inspection["Image"] = "sha256:" + "b" * 64
    elif drift == "container_change":
        spec = replace(
            spec,
            prior_evidence=replace(spec.prior_evidence, trusted_container_id="b" * 64),
        )
    elif drift == "runtime_change":
        spec = replace(spec, runtime_revision_id=str(uuid4()))
    spec = approved(spec, proof)
    if drift == "approval_exclusion_absent":
        spec = replace(spec, approval_check=None)
    with pytest.raises(
        (DockerDevelopmentSourceDeploymentError, RuntimeRevisionPreconditionError)
    ):
        fixture._apply(client, spec)
    assert not client.put_members


@pytest.mark.parametrize(
    "paths",
    [
        ("unchanged.py",),
        ("resources",),
        ("resources/missing.xml",),
        (PATH, PATH),
        ("../outside",),
        ("/absolute",),
    ],
)
def test_review_cannot_approve_original_missing_directory_or_unsafe_paths(
    tmp_path: Path, paths: tuple[str, ...]
) -> None:
    client, spec, _baseline, _proof = prepared(tmp_path)
    with pytest.raises(DockerDevelopmentSourceDeploymentError):
        DockerManagedContainerAdapter(lambda: client).review_source_additions(
            spec=spec, expected_container_id=fixture.CONTAINER_ID, paths=paths
        )
    assert not client.put_members


@pytest.mark.parametrize(
    "kind",
    [
        tarfile.SYMTYPE,
        tarfile.LNKTYPE,
        tarfile.FIFOTYPE,
        tarfile.CHRTYPE,
        tarfile.BLKTYPE,
    ],
)
def test_links_and_special_files_are_rejected_during_preview(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, kind: bytes
) -> None:
    client, spec, _baseline, proof = prepared(tmp_path)
    original = client.get_archive

    def archive(*args: Any) -> Any:
        chunks, metadata = original(*args)
        out = io.BytesIO()
        with (
            tarfile.open(fileobj=io.BytesIO(b"".join(chunks))) as source,
            tarfile.open(fileobj=out, mode="w") as target,
        ):
            for entry in source:
                if entry.name.endswith(PATH):
                    entry.type = kind
                    entry.size = 0
                    entry.linkname = "unchanged.py"
                    target.addfile(entry)
                else:
                    target.addfile(
                        entry, source.extractfile(entry) if entry.isfile() else None
                    )
        return [out.getvalue()], metadata

    monkeypatch.setattr(client, "get_archive", archive)
    with pytest.raises(DockerDevelopmentSourceDeploymentError):
        DockerManagedContainerAdapter(lambda: client).review_source_additions(
            spec=spec, expected_container_id=fixture.CONTAINER_ID, paths=(PATH,)
        )
    with pytest.raises(DockerDevelopmentSourceDeploymentError):
        fixture._apply(client, approved(spec, proof))
    assert not client.put_members


def test_second_preimage_catches_concurrent_change_before_write(tmp_path: Path) -> None:
    client, spec, _baseline, proof = prepared(tmp_path)

    def concurrent_change() -> None:
        client.entries[PATH] = (b"changed during staging", 0o644, 42, 43)

    with pytest.raises(DockerDevelopmentSourceDeploymentError):
        fixture._apply(
            client, replace(approved(spec, proof), approval_check=concurrent_change)
        )
    assert not client.put_members


@pytest.mark.parametrize("failure", ["readback", "identity", "preserved_file"])
def test_postcopy_failure_retains_reconciliation_requirement(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, failure: str
) -> None:
    client, spec, _baseline, proof = prepared(tmp_path)
    client.fail_readback_after_apply = failure == "readback"
    client.fail_final_inspect = failure == "identity"
    if failure == "preserved_file":
        put = client.put_archive

        def put_and_tamper(*args: Any) -> bool:
            result = put(*args)
            client.entries[PATH] = (b"tampered after copy", 0o644, 42, 43)
            return bool(result)

        monkeypatch.setattr(client, "put_archive", put_and_tamper)
    with pytest.raises(DockerDevelopmentSourceDeploymentError) as raised:
        fixture._apply(client, approved(spec, proof))
    assert raised.value.reconciliation_required is True
    assert client.put_members


def test_stale_retained_success_can_be_reviewed_but_unknown_cannot(
    tmp_path: Path,
) -> None:
    client, spec, _baseline, proof = prepared(tmp_path)
    stale = replace(
        spec,
        prior_evidence=replace(
            spec.prior_evidence, confidence=DevelopmentSourceDeploymentConfidence.STALE
        ),
    )
    fixture._apply(client, approved(stale, proof))
    unknown = replace(
        spec,
        prior_evidence=replace(
            spec.prior_evidence,
            confidence=DevelopmentSourceDeploymentConfidence.UNKNOWN,
        ),
    )
    with pytest.raises(DockerDevelopmentSourceDeploymentError):
        fixture._apply(client, approved(unknown, proof))
